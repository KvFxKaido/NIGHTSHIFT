async page => {
  page.setDefaultTimeout(30000);
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.setViewportSize({width:1500,height:1000});
  await page.goto('http://127.0.0.1:5173/editor.html');
  await page.waitForFunction(()=>document.body.dataset.editorReady==='true');
  const original = await page.evaluate(async()=>await (await fetch('/__editor/layout')).json());
  const selected = await page.locator('#building').inputValue();
  const height = Number(await page.locator('#height').inputValue());
  let wrote = false;
  try {
    // A real numeric edit, undo and redo through the UI.
    await page.locator('#height').fill(String(height + 2));
    await page.locator('#height').press('Tab');
    if(await page.locator('#save').isDisabled()) throw Error('Valid edit cannot be saved');
    await page.locator('#undo').click();
    if(Number(await page.locator('#height').inputValue())!==height)throw Error('Undo failed');
    await page.locator('#redo').click();
    await page.screenshot({path:'artifacts/editor-edited.png'});
    await page.locator('#save').click();
    await page.waitForFunction(()=>!document.getElementById('save-status').textContent.startsWith('Saving'));
    if(!(await page.locator('#save-status').textContent()).startsWith('Saved to project'))throw Error(await page.locator('#save-status').textContent());
    wrote = true;
    const saved = await page.evaluate(async()=>await (await fetch('/__editor/layout')).json());
    const placement = saved.layout.buildings.find(b=>b.id===selected);
    if(placement?.height!==height+2)throw Error('Saved file lost the edit');

    // Reload the actual game, not a separate mock of its world adapter.
    const game = await page.context().newPage();
    try {
      await game.goto('http://127.0.0.1:5173/?scene=track&freeze=1');
      await game.waitForFunction(()=>window.__ns&&document.body.dataset.assetState==='ready',null,{timeout:30000});
      const physics = await game.evaluate(async({id,height})=>{
        const {SEATTLE_BLOCKS,GENERATED_SEATTLE_BLOCKS,SEATTLE_VERSION}=await import('/src/sim/seattle.ts');
        const {buildingId}=await import('/src/sim/building-layout.ts');
        const index=GENERATED_SEATTLE_BLOCKS.findIndex(b=>buildingId(b)===id), block=SEATTLE_BLOCKS[index];
        __ns.sim.world.step();
        let hit=false;
        __ns.sim.world.intersectionsWithPoint({x:block.x,y:block.base+height-0.1,z:block.z},c=>{
          if(Math.abs(c.translation().x-block.x)<1e-3&&Math.abs(c.translation().z-block.z)<1e-3)hit=true;
          return true;
        });
        return {height:block.height,hit,version:SEATTLE_VERSION};
      },{id:selected,height:height+2});
      if(physics.height!==height+2||!physics.hit||!physics.version.includes('-layout-'))throw Error('Saved editor state did not reach game physics: '+JSON.stringify(physics));
    } finally { await game.close(); }

    // Export and re-import the actual Three.js JSON generated by the UI.
    await page.locator('summary').click();
    const download = page.waitForEvent('download');
    await page.locator('#export-scene').click();
    const sceneFile='artifacts/editor-roundtrip.json';
    await (await download).saveAs(sceneFile);
    await page.locator('#import-file').setInputFiles(sceneFile);
    await page.waitForFunction(()=>document.getElementById('save-status').textContent.startsWith('Imported as a draft'));
    if(await page.locator('#validation').getAttribute('data-invalid')==='true')throw Error('Scene round trip invalidated the buildings');

    // Put a building in the road and confirm both UI and server refuse the save.
    const point = await page.evaluate(async()=>{const{SEATTLE_STREETS}=await import('/src/sim/seattle.ts');return SEATTLE_STREETS[0].points[0];});
    await page.locator('#x').fill(String(point.x)); await page.locator('#x').press('Tab');
    await page.locator('#z').fill(String(point.z)); await page.locator('#z').press('Tab');
    if(await page.locator('#validation').getAttribute('data-invalid')!=='true'||!await page.locator('#save').isDisabled())throw Error('Overlapping placement was accepted');
    const rejected = await page.evaluate(async({saved,id,point})=>{
      const layout=structuredClone(saved.layout),block=layout.buildings.find(b=>b.id===id);block.x=point.x;block.z=point.z;
      const response=await fetch('/__editor/layout',{method:'PUT',headers:{'Content-Type':'application/json','If-Match':saved.revision},body:JSON.stringify(layout)});
      return {status:response.status,body:await response.json()};
    },{saved,id:selected,point});
    if(rejected.status!==400)throw Error('Endpoint accepted an overlapping footprint');
    await page.screenshot({path:'artifacts/editor-invalid.png'});
  } finally {
    // Restore the exact starting intent, including any pre-existing user placements.
    if(wrote) {
      const restored=await page.evaluate(async original=>{
        const latest=await(await fetch('/__editor/layout')).json();
        const response=await fetch('/__editor/layout',{method:'PUT',headers:{'Content-Type':'application/json','If-Match':latest.revision},body:JSON.stringify(original.layout)});
        return {ok:response.ok,result:await response.json()};
      },original);
      if(!restored.ok)throw Error('Could not restore starting layout: '+JSON.stringify(restored));
    }
    await page.locator('details').evaluate(node=>node.open=true);
    await page.locator('#reload-saved').click();
    await page.waitForFunction(()=>document.getElementById('save-status').textContent.startsWith('Loaded saved'));
    await page.reload();
    await page.waitForFunction(()=>document.body.dataset.editorReady==='true');
  }
  if(errors.length)throw Error(errors.join('\n'));
  await page.screenshot({path:'artifacts/editor-final.png'});
  return {passed:true,buildings:await page.locator('#building option').count(),savedToPhysics:true,threeJsonRoundTrip:true,overlapRejected:true,restored:true,errors};
}
